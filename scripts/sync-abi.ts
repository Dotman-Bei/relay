/**
 * Copies the compiled CapsuleRegistry ABI and bytecode from Foundry's output into
 * @relay/protocol-types, and records their hashes so deployments can cite ABI provenance.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const artifact = JSON.parse(
  readFileSync(resolve(root, "contracts/out/CapsuleRegistry.sol/CapsuleRegistry.json"), "utf8"),
);
const abi = artifact.abi as unknown[];
const bytecode = artifact.bytecode.object as string;
const deployedBytecode = artifact.deployedBytecode.object as string;

const sha256 = (s: string | Buffer) => createHash("sha256").update(s).digest("hex");
const abiJson = JSON.stringify(abi);
const abiSha256 = sha256(abiJson);
const deployedBytecodeSha256 = sha256(Buffer.from(deployedBytecode.replace(/^0x/, ""), "hex"));

const header = "// Generated by scripts/sync-abi.ts from contracts/out. Do not edit by hand.\n";
writeFileSync(
  resolve(root, "packages/protocol-types/src/abi.ts"),
  `${header}export const capsuleRegistryAbi = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
    `/** sha256 of the ABI JSON (compact). Recorded in deployment files as ABI provenance. */\n` +
    `export const CAPSULE_REGISTRY_ABI_SHA256 = "${abiSha256}";\n`,
);
writeFileSync(
  resolve(root, "packages/protocol-types/src/bytecode.ts"),
  `${header}export const capsuleRegistryBytecode = "${bytecode}" as const;\n` +
    `export const capsuleRegistryDeployedBytecode = "${deployedBytecode}" as const;\n` +
    `/** sha256 of the runtime bytecode; the web client and verifier compare it with eth_getCode. */\n` +
    `export const CAPSULE_REGISTRY_RUNTIME_SHA256 = "${deployedBytecodeSha256}";\n`,
);
console.log(`abi sha256 ${abiSha256}\nruntime sha256 ${deployedBytecodeSha256}`);
